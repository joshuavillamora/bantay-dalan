/* Generate the runtime catalog only from explicitly selected, validated assets. */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const [directory, ...ids] = process.argv.slice(2);
assert.ok(directory && ids.length && new Set(ids).size === ids.length, 'Usage: node scripts/build-region-manifest.mjs REPORT_DIRECTORY REGION_ID...');
const rows = ids.map(id => {
  const report = JSON.parse(readFileSync(join(directory, id + '.verified.json'), 'utf8'));
  assert.ok(!report.deferred && report.verified?.length && report.repaired && report.analysis?.trips === 6, id + ' did not pass verification');
  assert.equal(report.manifest.id, id);
  return report.manifest;
});
console.log('// Generated by scripts/build-region-manifest.mjs. See data/regional-coverage.md.');
console.log('export const additionalRegions = [');
console.log(rows.map(region => '  ' + JSON.stringify(region)).join(',\n'));
console.log('];');
