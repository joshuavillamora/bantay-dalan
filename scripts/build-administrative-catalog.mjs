/* Stage only administrative graphs that passed the regional verifier. */
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gunzipSync, gzipSync } from 'node:zlib';
import { administrativeGroups } from '../data/regions/administrative.js';
import { boundsContain } from './administrative-geometry.mjs';

const [roads, places, reports, boundaries, output, ...requested] = process.argv.slice(2);
assert.ok(output && requested.length, 'Pass road, place, verification, boundary and output paths, then the validated dataset IDs');
const digest = data => createHash('sha256').update(data).digest('hex');
const zip = value => gzipSync(JSON.stringify(value), { level: 9 });
const shapes = readFileSync(boundaries);
const published = new Map(JSON.parse(shapes).features.map(feature => [
  feature.properties.scope ?? 'ph-' + feature.properties.adm1_psgc, feature
]));
const roster = new Map(administrativeGroups.flatMap(([group, entries]) => entries.map(([id, name]) => [id, { name, group }])));
const catalog = [], placeRecords = [];
for (const directory of ['data/regions', 'data/regions/coverage', 'data/places']) {
  mkdirSync(join(output, directory), { recursive: true });
}
for (const id of requested) {
  const region = roster.get(id), boundary = published.get(id);
  assert.ok(region && boundary && !catalog.some(row => row.id === id), 'Invalid or duplicate dataset: ' + id);
  const proof = JSON.parse(readFileSync(join(reports, id + '.json')));
  assert.ok(proof.verified?.length && proof.repaired && proof.analysis?.trips === 6 && !proof.deferred, id + ' did not pass verification');
  const manifest = proof.manifest;
  assert.equal(manifest.id, id);
  assert.equal(manifest.name, region.name);
  const roadsGzip = readFileSync(join(roads, id + '.json.gz'));
  assert.equal(digest(roadsGzip), manifest.sha256);
  const source = JSON.parse(gunzipSync(roadsGzip));
  assert.equal(source.boundarySha256, digest(shapes));
  const index = JSON.parse(gunzipSync(readFileSync(join(places, id + '.json.gz'))));
  assert.equal(index.pbfSha256, manifest.source);
  assert.equal(index.snapshot, manifest.version);
  index.entries = index.entries.filter(([, , lat, lng]) => boundsContain(manifest.bounds, lat / 1e6, lng / 1e6));
  assert.ok(index.entries.length, 'Empty place index: ' + id);
  const placeGzip = zip(index), coverageGzip = zip(boundary);
  const placeUrl = `data/places/${id}.json.gz`;
  const coverageUrl = `data/regions/coverage/${id}.geojson.gz`;
  writeFileSync(join(output, manifest.url), roadsGzip);
  writeFileSync(join(output, placeUrl), placeGzip);
  writeFileSync(join(output, coverageUrl), coverageGzip);
  placeRecords.push({ id, records: index.entries.length, bytes: placeGzip.length, sha256: digest(placeGzip) });
  catalog.push({ ...manifest, group: region.group, placeUrl, coverageUrl, coverageSha256: digest(coverageGzip),
    boundarySha256: source.boundarySha256 });
}
writeFileSync(join(output, 'data/regions/administrative-manifest.js'),
  '// Generated by scripts/build-administrative-catalog.mjs.\nexport const administrativeRegions = [\n' +
  catalog.map(row => '  ' + JSON.stringify(row)).join(',\n') + '\n];\n');
writeFileSync(join(output, 'place-catalog.json'), JSON.stringify(placeRecords) + '\n');
